//! C Header prototype generator for Valerie procedures.
//!
//! Inspects procedure signatures, register parameters, and ABI requirements
//! to generate 100% standard C/C++ compatible headers (`.h`).

use crate::vale_bridge::ValeProcedure;
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as FmtWrite;

/// Header generation configuration.
#[derive(Debug, Clone, Default)]
pub struct HeaderConfig {
    pub description: Option<String>,
    pub package_prefix: Option<String>,
}

/// Infers the active GPR arguments used in a procedure based on input registers.
pub fn infer_procedure_params(proc: &ValeProcedure) -> Vec<(String, String)> {
    let (_, params) = infer_procedure_signature(proc);
    params
}

/// Infers the return type and parameter types for a Vale procedure.
pub fn infer_procedure_signature(
    proc: &ValeProcedure,
) -> (String, Vec<(String, String)>) {
    let mut reg_widths: BTreeMap<u8, bool> = BTreeMap::new(); // true = 64-bit, false = 32-bit
    let mut reg_byte_ops: BTreeSet<u8> = BTreeSet::new();

    let lower_name = proc.name.to_lowercase();
    let returns_u128 = lower_name.contains("128")
        || lower_name.contains("rev128")
        || lower_name.contains("fsquare");

    for inst in &proc.instructions {
        let lower = inst.to_lowercase();
        let is_byte = lower.contains("uxtb")
            || lower.contains("sxtb")
            || lower.contains("ldrb")
            || lower.contains("strb");

        for i in 0..8 {
            let x_reg = format!("x{}", i);
            let w_reg = format!("w{}", i);
            let r_reg = format!("r{}", i);
            if lower.contains(&x_reg) {
                reg_widths.insert(i, true);
                if is_byte {
                    reg_byte_ops.insert(i);
                }
            } else if lower.contains(&w_reg) || lower.contains(&r_reg) {
                reg_widths.entry(i).or_insert(false);
                if is_byte {
                    reg_byte_ops.insert(i);
                }
            }
        }
    }

    let ret_type = if returns_u128 {
        "FStar_UInt128_t".to_string()
    } else if lower_name.starts_with("get_")
        || lower_name.starts_with("read_")
        || lower_name.starts_with("load_")
        || lower_name.starts_with("hash_")
        || lower_name.starts_with("crc_")
    {
        if reg_widths.get(&0) == Some(&false) {
            if reg_byte_ops.contains(&0) {
                "uint8_t".to_string()
            } else {
                "uint32_t".to_string()
            }
        } else {
            "uint64_t".to_string()
        }
    } else {
        "void".to_string()
    };

    let mut params = Vec::new();
    for (&idx, &is_64) in &reg_widths {
        let ty = if reg_byte_ops.contains(&idx) && !is_64 {
            "uint8_t"
        } else if is_64 {
            "uint64_t"
        } else {
            "uint32_t"
        };
        params.push((ty.to_string(), format!("arg{}", idx)));
    }

    if params.is_empty() {
        params.push(("void".to_string(), String::new()));
    }

    (ret_type, params)
}

/// Generates a complete, standard C/C++ header for an array of Vale procedures with custom configuration.
pub fn generate_c_header_with_config(
    guard_name: &str,
    procs: &[ValeProcedure],
    config: &HeaderConfig,
) -> String {
    let mut out = String::new();

    let clean_stem = guard_name
        .to_uppercase()
        .chars()
        .map(|c| if c.is_alphanumeric() { c } else { '_' })
        .collect::<String>();

    let full_guard = match &config.package_prefix {
        Some(pkg) if !pkg.trim().is_empty() => {
            let clean_pkg = pkg
                .trim()
                .to_uppercase()
                .chars()
                .map(|c| if c.is_alphanumeric() { c } else { '_' })
                .collect::<String>();
            format!("{}_{}", clean_pkg, clean_stem)
        }
        _ => clean_stem,
    };

    let desc = config.description.as_deref().unwrap_or(
        "Direct 1:1 C ABI prototypes for unoptimized assembly procedures",
    );

    let _ = writeln!(out, "/*");
    let _ = writeln!(
        out,
        " * Generated by Valerie - Unoptimized Assembly Emitter & Translation Validation Engine"
    );
    let _ = writeln!(out, " * {}", desc);
    let _ = writeln!(out, " */");
    let _ = writeln!(out, "#ifndef {}_H", full_guard);
    let _ = writeln!(out, "#define {}_H\n", full_guard);
    let _ = writeln!(out, "#include <stdint.h>");
    let _ = writeln!(out, "#include <stddef.h>");
    let _ = writeln!(out, "#include \"krmllib.h\"\n");
    let _ = writeln!(out, "#ifdef __cplusplus");
    let _ = writeln!(out, "extern \"C\" {{");
    let _ = writeln!(out, "#endif\n");

    for proc in procs {
        let (ret_type, params) = infer_procedure_signature(proc);

        let param_str = if params.len() == 1 && params[0].0 == "void" {
            "void".to_string()
        } else {
            params
                .iter()
                .map(|(ty, name)| format!("{} {}", ty, name))
                .collect::<Vec<_>>()
                .join(", ")
        };

        let _ = writeln!(out, "/**");
        let _ = writeln!(out, " * @brief Procedure `{}`", proc.name);
        let _ =
            writeln!(out, " * Formally verified under F* operational semantics.");
        let _ = writeln!(out, " */");
        let _ = writeln!(out, "{} {}({});\n", ret_type, proc.name, param_str);
    }

    let _ = writeln!(out, "#ifdef __cplusplus");
    let _ = writeln!(out, "}}");
    let _ = writeln!(out, "#endif\n");
    let _ = writeln!(out, "#endif /* {}_H */", full_guard);

    out
}

pub fn generate_c_header(guard_name: &str, procs: &[ValeProcedure]) -> String {
    generate_c_header_with_config(guard_name, procs, &HeaderConfig::default())
}
